CREATE TABLE IF NOT EXISTS RAG_SOURCE_DOCUMENT (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CREATED_ON TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_ON TIMESTAMP WITH TIME ZONE NOT NULL,
    IS_ACTIVE BOOLEAN NOT NULL,
    IS_DELETED BOOLEAN NOT NULL,
    SOURCE_NAME VARCHAR(255) NOT NULL,
    EXTERNAL_ID VARCHAR(255) NOT NULL,
    TENANT_ID VARCHAR(128) NOT NULL DEFAULT 'default',
    CONTENT_HASH VARCHAR(128) NOT NULL,
    CHUNK_COUNT INTEGER NOT NULL,
    CONSTRAINT UK_RAG_SOURCE_DOCUMENT UNIQUE (SOURCE_NAME, EXTERNAL_ID, TENANT_ID)
);

CREATE TABLE IF NOT EXISTS RAG_INGESTION_JOB (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CREATED_ON TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_ON TIMESTAMP WITH TIME ZONE NOT NULL,
    IS_ACTIVE BOOLEAN NOT NULL,
    IS_DELETED BOOLEAN NOT NULL,
    SOURCE_NAME VARCHAR(255) NOT NULL,
    STATUS VARCHAR(16) NOT NULL,
    STARTED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    FINISHED_AT TIMESTAMP WITH TIME ZONE,
    ADDED_COUNT INTEGER NOT NULL DEFAULT 0,
    UPDATED_COUNT INTEGER NOT NULL DEFAULT 0,
    DELETED_COUNT INTEGER NOT NULL DEFAULT 0,
    SKIPPED_COUNT INTEGER NOT NULL DEFAULT 0,
    ERROR_MESSAGE VARCHAR(500)
);

CREATE INDEX IF NOT EXISTS IDX_RAG_JOB_SOURCE_CREATED ON RAG_INGESTION_JOB (SOURCE_NAME, CREATED_ON);
